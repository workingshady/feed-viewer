import { appendFileSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { it } from "vitest";
import { trainMatchModel, type TrainingInput } from "@/lib/matchTraining";
import { MATCH_WEIGHTS } from "@/lib/propertyMatchWeights";
import type { Listing } from "@/lib/types";

/**
 * Runs the app's own trainer (the code the background retrain uses) on real feeds from disk: proves it
 * works end to end, reports accuracy and run time, and with BENCH_WRITE=1 refreshes the built-in
 * weights shipped with the app (src/lib/propertyMatchWeights.ts).
 *
 *   BENCH_CACHE      JSON cache from dump.bench.test.ts (run__<spider>__old/new, agency__<name>)
 *   BENCH_PROGRESS   optional file for progress lines (vitest buffers console output)
 */
const cache = process.env.BENCH_CACHE ?? "";
const progress = (msg: string) => process.env.BENCH_PROGRESS && appendFileSync(process.env.BENCH_PROGRESS, `${new Date().toISOString().slice(11, 19)} ${msg}\n`);
const load = (f: string): Listing[] => JSON.parse(readFileSync(path.join(cache, f), "utf8")).listings;

it("trains the matching model on real feeds", () => {
  const files = readdirSync(cache);
  const spiders = [...new Set(files.filter((f) => f.startsWith("run__")).map((f) => f.split("__")[1]))];
  const versions: TrainingInput["versions"] = [];
  for (const s of spiders) {
    const o = `run__${s}__old.json`;
    const n = `run__${s}__new.json`;
    if (files.includes(o) && files.includes(n)) versions.push({ old: load(o), new: load(n) });
  }
  if (files.includes("bh_old.json") && files.includes("bh_b.json")) versions.push({ old: load("bh_old.json"), new: load("bh_b.json") });
  const agencies = files.filter((f) => f.startsWith("agency__")).map((f) => ({ group: f.slice(8, -5), listings: load(f) }));
  progress(`loaded ${versions.length} version pairs, ${agencies.length} agencies`);

  const t = Date.now();
  const res = trainMatchModel({ versions, agencies, labels: [], current: MATCH_WEIGHTS, progress });
  const m = res.metrics;
  const line = (k: "versions" | "agencies") =>
    `${k}: precision ${(m[k].precision * 100).toFixed(1)}% recall ${(m[k].recall * 100).toFixed(1)}% (active model ${(m[k].currentPrecision * 100).toFixed(1)}% / ${(m[k].currentRecall * 100).toFixed(1)}%)`;
  progress(`${line("versions")} || ${line("agencies")} || thresholds v ${res.weights.versions.match}/${res.weights.versions.possible} a ${res.weights.agencies.match}/${res.weights.agencies.possible} || gate ${m.gate.passed ? "passed" : "held back"}: ${m.gate.reason} || ${((Date.now() - t) / 1000).toFixed(0)} s`);

  if (process.env.BENCH_WRITE === "1") {
    const file = path.resolve(__dirname, "../src/lib/propertyMatchWeights.ts");
    writeFileSync(
      file,
      `/* Generated by bench/train.bench.test.ts on ${new Date().toISOString().slice(0, 10)} with the in-app trainer (src/lib/matchTraining.ts). */
import type { MatchSignal } from "@/lib/propertyMatch";

export type WeightTable = { match: number; possible: number; weights: Partial<Record<MatchSignal, Record<string, number>>> };

/**
 * Built-in model: used until the server has an active trained one. log2(m/u) weights learned from
 * permit-matched pairs (m) and random look-alike pairs (u) in real feeds; thresholds measured by
 * replaying the real jobs with permits hidden. Versions: ${line("versions")}.
 * Across agencies a shared permit is required for "match"; the rest goes to review.
 */
export const MATCH_WEIGHTS: Record<"versions" | "agencies", WeightTable> = ${JSON.stringify(res.weights, null, 2)};
`,
    );
  }
  progress("done");
});
